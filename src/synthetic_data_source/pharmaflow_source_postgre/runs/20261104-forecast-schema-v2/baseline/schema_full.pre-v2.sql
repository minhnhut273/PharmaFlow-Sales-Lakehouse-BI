-- Classify a lot on an explicit evaluation date. The warning window is supplied
-- by the caller; a missing expiry date remains unknown, not implicitly sellable.
CREATE OR REPLACE FUNCTION inventory.lot_expiry_status(
    p_expiry_date DATE,
    p_evaluation_date DATE,
    p_warning_days INTEGER DEFAULT 0
) RETURNS TEXT
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_evaluation_date IS NULL OR p_warning_days IS NULL OR p_warning_days < 0 THEN
        RAISE EXCEPTION 'evaluation date is required and warning days must be nonnegative';
    END IF;
    IF p_expiry_date IS NULL THEN
        RETURN 'UNKNOWN_EXPIRY';
    ELSIF p_expiry_date < p_evaluation_date THEN
        RETURN 'EXPIRED';
    ELSIF p_expiry_date = p_evaluation_date THEN
        RETURN 'EXPIRING_TODAY';
    ELSIF p_expiry_date <= p_evaluation_date + p_warning_days THEN
        RETURN 'NEAR_EXPIRY';
    END IF;
    RETURN 'IN_DATE';
END;
$$;

