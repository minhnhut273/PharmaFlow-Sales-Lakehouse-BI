           (movement_type IN ('EXPIRY_WRITE_OFF', 'OPENING_BALANCE', 'OTHER') AND num_nonnulls(sales_order_line_id, goods_receipt_line_id, stock_transfer_line_id, stock_take_line_id) = 0))
