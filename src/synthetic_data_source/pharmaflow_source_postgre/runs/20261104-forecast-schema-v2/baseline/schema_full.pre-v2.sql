    warehouse_id          BIGINT NOT NULL REFERENCES org.warehouse(warehouse_id),
    batch_lot_id          BIGINT NOT NULL REFERENCES inventory.batch_lot(batch_lot_id),
    movement_type         TEXT NOT NULL CHECK (movement_type IN ('SALE_RETAIL', 'GOODS_RECEIPT', 'TRANSFER_OUT', 'TRANSFER_IN', 'STOCKTAKE_ADJUSTMENT', 'EXPIRY_WRITE_OFF', 'OPENING_BALANCE', 'OTHER')),
    quantity_delta        NUMERIC(18,4) NOT NULL CHECK (quantity_delta <> 0),
    occurred_at           TIMESTAMPTZ NOT NULL,
    sales_order_line_id   BIGINT REFERENCES pos.sales_order_line(sales_order_line_id),
    goods_receipt_line_id BIGINT REFERENCES procurement.goods_receipt_line(goods_receipt_line_id),
    stock_transfer_line_id BIGINT REFERENCES inventory.stock_transfer_line(stock_transfer_line_id),
    stock_take_line_id    BIGINT REFERENCES inventory.stock_take_line(stock_take_line_id),
    adjustment_reason     TEXT,
    data_origin           TEXT NOT NULL CHECK (data_origin IN ('OBSERVED_PUBLIC', 'OBSERVED_DATASET', 'DERIVED', 'SYNTHETIC')),
