-- CONSOLIDATED PharmaFlow source schema package.
--
-- This is a one-time bootstrap script for a NEW, EMPTY PostgreSQL database.
-- It combines the current local source baseline with every source migration,
-- including the not-yet-deployed workflow contract proposal 20261024_03.
-- It is NOT a description of the current Neon production schema and must not
-- be run against production. The proposal adds return/recall/quality/request
-- structures and changes inventory semantics. Review its source contract first.
--
-- The archived schema_v1.sql already incorporates the effective DDL of
-- migrations 20260930_01, 20260930_02, and 20261103_04. Those migration files
-- are retained in archive/2026-11-03-source-sql-history/ and are not replayed.
-- The proposal migration 20261024_03 is appended below, without its own
-- transaction wrapper, so this complete bootstrap runs atomically.

BEGIN;
-- PharmaFlow retail-pharmacy operational source simulator, v1.
-- This is a separate source database from archive/2026-11-03-downstream-dss-temporary/pharmaflow_downstream/schema.sql,
-- which models downstream observations, forecasts, decisions, and KPI outputs.
-- Public Long Chau pages are observations; simulated POS/procurement/inventory
-- rows are not actual Long Chau transactions.

CREATE SCHEMA IF NOT EXISTS catalog;
CREATE SCHEMA IF NOT EXISTS org;
CREATE SCHEMA IF NOT EXISTS pos;
CREATE SCHEMA IF NOT EXISTS procurement;
CREATE SCHEMA IF NOT EXISTS inventory;

-- Foreign keys intentionally keep PostgreSQL's default ON DELETE NO ACTION.
-- Referenced product and transaction history cannot be deleted by cascading.

-- catalog: generic product master with separate source and taxonomy evidence.
CREATE TABLE catalog.manufacturer (
    manufacturer_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer_code     TEXT UNIQUE,
    manufacturer_name     TEXT NOT NULL,
    country_code          TEXT,
    data_origin           TEXT NOT NULL CHECK (data_origin IN ('OBSERVED_PUBLIC', 'OBSERVED_DATASET', 'DERIVED', 'SYNTHETIC')),
    source_ref            TEXT,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE catalog.unit_of_measure (
    uom_code              TEXT PRIMARY KEY,
    uom_name              TEXT NOT NULL,
    uom_kind              TEXT NOT NULL CHECK (uom_kind IN ('COUNT', 'MASS', 'VOLUME', 'PACKAGE', 'OTHER')),
    data_origin           TEXT NOT NULL CHECK (data_origin IN ('OBSERVED_PUBLIC', 'OBSERVED_DATASET', 'DERIVED', 'SYNTHETIC')),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE catalog.product_category (
    category_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    taxonomy_scheme       TEXT NOT NULL CHECK (taxonomy_scheme IN ('LONGCHAU_PUBLIC', 'PHARMAFLOW_BUSINESS', 'ATC')),
    category_code         TEXT NOT NULL,
    category_name         TEXT NOT NULL,
    parent_category_id    BIGINT,
    source_category_path  TEXT,
    is_active             BOOLEAN NOT NULL DEFAULT TRUE,
    data_origin           TEXT NOT NULL CHECK (data_origin IN ('OBSERVED_PUBLIC', 'OBSERVED_DATASET', 'DERIVED', 'SYNTHETIC')),
    UNIQUE (taxonomy_scheme, category_code),
    UNIQUE (category_id, taxonomy_scheme),
    FOREIGN KEY (parent_category_id, taxonomy_scheme)
        REFERENCES catalog.product_category(category_id, taxonomy_scheme)
);

CREATE TABLE catalog.product (
    product_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code          TEXT NOT NULL UNIQUE,
    product_name          TEXT NOT NULL,
    product_kind          TEXT NOT NULL CHECK (product_kind IN ('MEDICINE', 'SUPPLEMENT', 'MEDICAL_DEVICE', 'OTHER')),
    brand_name            TEXT,
    dosage_form           TEXT,
    active_ingredient_text TEXT,
    strength_text         TEXT,
    prescription_status   TEXT CHECK (prescription_status IN ('PRESCRIPTION', 'NON_PRESCRIPTION', 'UNKNOWN')),
    registration_number   TEXT,
    manufacturer_id       BIGINT REFERENCES catalog.manufacturer(manufacturer_id),
    base_uom_code         TEXT REFERENCES catalog.unit_of_measure(uom_code),
    is_active             BOOLEAN NOT NULL DEFAULT TRUE,
    data_origin           TEXT NOT NULL CHECK (data_origin IN ('OBSERVED_PUBLIC', 'OBSERVED_DATASET', 'DERIVED', 'SYNTHETIC')),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE catalog.product_category_assignment (
    product_id            BIGINT NOT NULL REFERENCES catalog.product(product_id),
    category_id           BIGINT NOT NULL REFERENCES catalog.product_category(category_id),
    assignment_status     TEXT NOT NULL CHECK (assignment_status IN ('VERIFIED', 'CANDIDATE')),
    assignment_basis      TEXT NOT NULL,
    data_origin           TEXT NOT NULL CHECK (data_origin IN ('OBSERVED_PUBLIC', 'OBSERVED_DATASET', 'DERIVED', 'SYNTHETIC')),
    assigned_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (product_id, category_id)
);

CREATE TABLE catalog.product_source_reference (
    product_source_reference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id            BIGINT REFERENCES catalog.product(product_id),
    source_system_key     TEXT NOT NULL,
    external_product_key  TEXT NOT NULL,
    observed_name         TEXT,
    source_category_path  TEXT,
    canonical_url         TEXT,
    observed_list_price  NUMERIC(18,2) CHECK (observed_list_price IS NULL OR observed_list_price >= 0),
    observed_sale_price  NUMERIC(18,2) CHECK (observed_sale_price IS NULL OR observed_sale_price >= 0),
    price_currency        CHAR(3),
    availability_status   TEXT,
    observed_attributes   JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(observed_attributes) = 'object'),
    source_url            TEXT,
    match_status          TEXT NOT NULL CHECK (match_status IN ('DIRECT', 'REVIEWED_MATCH', 'CANDIDATE', 'UNMATCHED', 'NOT_APPLICABLE')),
    match_basis           TEXT,
    data_origin           TEXT NOT NULL CHECK (data_origin IN ('OBSERVED_PUBLIC', 'OBSERVED_DATASET', 'DERIVED', 'SYNTHETIC')),
    observed_at           TIMESTAMPTZ NOT NULL,
    source_record_key     TEXT,
    UNIQUE (source_system_key, external_product_key, observed_at),
    CHECK ((product_id IS NULL AND match_status IN ('UNMATCHED', 'NOT_APPLICABLE')) OR
